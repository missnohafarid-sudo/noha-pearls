function describeKinds(): string {
  return SLIDE_KIND_NAMES.map((kind) => {
    const fields = slideKindSpec(kind).fileFields
      .filter((field) => field.name !== 'kind')
      .map((field) => `   - "${field.name}"${field.required ? ' (مطلوب)' : ''}: ${FIELD_HELP[field.name]}`)
      .join('\n');
    return `• "kind": "${kind}" (${slides.kind[kind]})\n${fields}`;
  }).join('\n\n');
}

